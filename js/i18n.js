let currentLanguage = 'en';

function getTranslation(key) {
  if (I18N_DATA[currentLanguage] && I18N_DATA[currentLanguage][key]) {
    return I18N_DATA[currentLanguage][key];
  }
  return I18N_DATA['en'][key] || key;
}

function setLanguage(langCode) {
  if (I18N_DATA[langCode]) {
    currentLanguage = langCode;
    localStorage.setItem('smriti_lang', langCode);
    updateDOMTranslations();
    
    // Announce language change via Web Speech if enabled
    if (window.speechEngine) {
      window.speechEngine.speakWelcome();
    }
  }
}

function updateDOMTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const text = getTranslation(key);
    if (text) {
      if (el.tagName === 'INPUT' && el.getAttribute('placeholder')) {
        el.setAttribute('placeholder', text);
      } else {
        el.textContent = text;
      }
    }
  });

  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    const text = getTranslation(key);
    if (text) el.setAttribute('title', text);
  });
}

// Auto-load persisted language preference
document.addEventListener('DOMContentLoaded', () => {
  const saved = localStorage.getItem('smriti_lang');
  if (saved && I18N_DATA[saved]) {
    currentLanguage = saved;
    const select = document.getElementById('globalLangSelect');
    if (select) select.value = saved;
  }
  updateDOMTranslations();
});
